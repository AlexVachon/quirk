import gzip, sys
src, out = sys.argv[1], sys.argv[2]
data = gzip.open(src).read()
assert data[0] == 0x36 and data[1] == 0x04
mode, size = data[2], data[3]
n = 512 if mode & 1 else 256
glyphs = data[4:4 + n * size]
table = data[4 + n * size:]
# Unicode table: per glyph, UCS-2 LE values until 0xFFFF (0xFFFE starts sequences).
cp2g = {}
i = 0
for g in range(n):
    seq = False
    while True:
        v = table[i] | (table[i + 1] << 8); i += 2
        if v == 0xFFFF: break
        if v == 0xFFFE: seq = True; continue
        if not seq and v not in cp2g: cp2g[v] = g
cps = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100))
missing = [hex(c) for c in cps if c not in cp2g]
assert not missing, missing
with open(out, "w") as f:
    f.write("// Generated by tools/gen_window_font.py from the Linux console font\n")
    f.write("// Uni2-Fixed16 (X11 misc-fixed 8x16, public domain). Do not edit.\n")
    f.write("// 8x16 glyphs, one byte per row, MSB = leftmost pixel.\n")
    f.write("// Index: codepoints 0x20-0x7E, then 0xA0-0xFF.\n\n")
    f.write("#define QFONT_W 8\n#define QFONT_H %d\n\n" % size)
    f.write("static const unsigned char qfont_glyphs[%d][%d] = {\n" % (len(cps), size))
    for c in cps:
        g = cp2g[c]
        rows = glyphs[g * size:(g + 1) * size]
        ch = chr(c) if c < 0x7F and c not in (0x5C,) else "U+%04X" % c
        f.write("    {" + ",".join("0x%02x" % b for b in rows) + "},  // %s\n" % ch)
    f.write("};\n\n")
    f.write("// Glyph index for codepoint `cp`, or the '?' glyph.\n")
    f.write("static int qfont_index(unsigned cp) {\n")
    f.write("    if (cp >= 0x20 && cp <= 0x7E) return (int)(cp - 0x20);\n")
    f.write("    if (cp >= 0xA0 && cp <= 0xFF) return (int)(cp - 0xA0) + 95;\n")
    f.write("    return '?' - 0x20;\n}\n")
print("glyphs:", len(cps), "height:", size)
